#!/usr/bin/env node
// Bundles the shared graph engine (src/lib/graph/engine.ts) into a
// dependency-free IIFE at cli/internal/serve/assets/graph.js, which the Go
// binary embeds — `kaioken serve` cannot run node, so the artifact is built
// here and committed. Mirrors build-sidecar.mjs, which crosses the same
// desktop↔cli boundary in the other direction.
//
//   node scripts/build-graph-asset.mjs          # (re)build the artifact
//   node scripts/build-graph-asset.mjs --check  # CI: fail if it is stale
import { buildSync } from "esbuild"
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const desktopRoot = join(here, "..")
const entry = join(desktopRoot, "src", "lib", "graph", "engine.ts")
const outFile = join(desktopRoot, "..", "cli", "internal", "serve", "assets", "graph.js")

const banner =
  "// GENERATED by desktop/scripts/build-graph-asset.mjs — do not edit.\n" +
  "// Source: desktop/src/lib/graph/. Rebuild: node scripts/build-graph-asset.mjs"

const result = buildSync({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: "iife",
  globalName: "KaioGraph",
  platform: "browser",
  target: "es2020",
  minify: true,
  legalComments: "none",
  banner: { js: banner },
})

const built = result.outputFiles[0].text

if (process.argv.includes("--check")) {
  const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : ""
  if (current !== built) {
    console.error(
      "build-graph-asset: cli/internal/serve/assets/graph.js is stale.\n" +
        "Run `node scripts/build-graph-asset.mjs` from desktop/ and commit the result."
    )
    process.exit(1)
  }
  console.log("build-graph-asset: artifact is up to date")
  process.exit(0)
}

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, built)
console.log(`build-graph-asset: wrote ${outFile} (${(built.length / 1024).toFixed(1)} KiB)`)
